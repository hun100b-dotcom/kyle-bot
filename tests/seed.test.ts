// tests/seed.test.ts — 세션별 시드 진입 수량 계산 테스트 (v0.3.0)
// -----------------------------------------------------------------------------
// [무엇을 검증하나?]
//   "지금 장에서 시드의 몇 %로 몇 주 살 수 있나"를 계산하는 computeSeedQty가
//   요구된 공식대로 동작하는지 고정한다. 이 값은 화면에 '제안 수량'으로 뜨고,
//   오너가 [적용]을 누르면 수량칸에 들어간다. 강제는 아니지만 숫자가 틀리면 안 된다.
//
//   공식: floor( 시드 × (세션%/100) ÷ ( 현재가 × (1+수수료율) ) )
// =============================================================================

import { describe, it, expect } from "vitest";
import { computeSeedQty } from "../electron/tool-engine";

describe("세션별 시드 진입 수량(computeSeedQty)", () => {
  it("데이마켓 90% · 시드 $1,000 · 현재가 $10 · 수수료 0 → 90주", () => {
    // 1000 × 0.9 = 900, 900 ÷ 10 = 90
    expect(computeSeedQty(1000, 90, 10, 0)).toBe(90);
  });

  it("프리마켓 50% · 시드 $1,000 · 현재가 $10 → 50주", () => {
    expect(computeSeedQty(1000, 50, 10, 0)).toBe(50);
  });

  it("본장 50% · 시드 $500 · 현재가 $7 → 35주(내림)", () => {
    // 500 × 0.5 = 250, 250 ÷ 7 = 35.7 → 내림 35
    expect(computeSeedQty(500, 50, 7, 0)).toBe(35);
  });

  it("수수료가 있으면 1주 실비용이 커져 수량이 줄 수 있다", () => {
    // 시드 100% 전액, 현재가 $100, 수수료 0.1%(0.001) → 1주 실비용 $100.1
    // 1000 ÷ 100.1 = 9.99 → 내림 9 (수수료 없으면 10)
    expect(computeSeedQty(1000, 100, 100, 0)).toBe(10);
    expect(computeSeedQty(1000, 100, 100, 0.001)).toBe(9);
  });

  it("시드가 없거나(자동인데 예수금 조회 실패) 0이면 null", () => {
    expect(computeSeedQty(null, 90, 10, 0)).toBeNull();
    expect(computeSeedQty(0, 90, 10, 0)).toBeNull();
  });

  it("현재가가 없거나 0이면 null(0으로 나눌 수 없음)", () => {
    expect(computeSeedQty(1000, 90, null, 0)).toBeNull();
    expect(computeSeedQty(1000, 90, 0, 0)).toBeNull();
  });

  it("세션 비율 0%면 0주(주문 안 함)", () => {
    expect(computeSeedQty(1000, 0, 10, 0)).toBe(0);
  });

  it("소수주는 내림되어 정수 제안이 된다(과다 매수 방지)", () => {
    // 1000 × 0.9 = 900, ÷ 327 = 2.75 → 2주
    expect(computeSeedQty(1000, 90, 327, 0)).toBe(2);
  });
});
