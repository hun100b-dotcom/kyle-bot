// 브라우저 안에서는 서버를 띄울 수 없습니다(연습 모드가 그걸 시도합니다).
// 그냥 두면 "cs.default.createServer is not a function" 처럼 알 수 없는 오류가 나서
// 사장님이 원인을 짐작할 수 없습니다. 그래서 무슨 일인지 한국어로 알려 줍니다.
// =============================================================================

function notSupported(): never {
  throw new Error(
    "연습(모의) 모드는 웹앱에서 쓸 수 없습니다(브라우저 안에서는 가짜 서버를 띄울 수 없습니다).\n\n" +
      "[설정] 탭에서 토스 키를 저장하면 실서버 모드로 전환됩니다. 연습이 필요하면 PC용 Capri를 사용하세요.",
  );
}

export const createServer = notSupported;
export default { createServer: notSupported };
