// -----------------------------------------------------------------------------
// [왜 따로 뺐나]
//   받기 결과를 "정상 / 클라우드에 아직 없음 / 진짜 실패" 셋으로 나누는 판단이 이 기능의 안전장치 핵심이다.
//   진짜 실패(복호화 실패·네트워크 오류)인데 그냥 올려 버리면, 다른 기기가 올려 둔 기록을 이 기기 것으로
//   덮어써서 지울 수 있다. 반대로 '빈 채널'(클라우드에 한 번도 올린 적 없음)을 실패로 보면 첫 업로드가 영영 안 된다.
//   네트워크 없이 테스트할 수 있도록 순수 함수로 둔다.
// =============================================================================

export type PullOutcome = "ok" | "empty" | "fail";

/**
 * classifyPullResult — syncPullTrades/AutoState/Splits 가 돌려준 {ok, message}를 세 가지로 분류한다.
 *   · ok    : 받아서 합쳤다.
 *   · empty : 클라우드에 이 계정의 기록이 아직 없다(정상 — 이 기기가 처음 올리면 된다).
 *   · fail  : 그 밖의 모든 실패. 이때는 올리기를 보류한다(덮어쓰기 사고 방지).
 */
export function classifyPullResult(r: { ok: boolean; message: string }): PullOutcome {
  if (r.ok) return "ok";
  // 각 pull 함수의 '행이 없음' 문구: "내 계정에 저장된 ... 없습니다"
  if (/저장된 .*없습니다/.test(r.message)) return "empty";
  return "fail";
}
