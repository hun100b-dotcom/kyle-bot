//   붙은 별도 종목으로 거래되는 관행이 있어, 그 흔한 접미사들을 추측해 실제로 시세가 있는지
//   확인하는 방식을 쓴다. **이 방식은 틀릴 수 있다**(회사마다 접미사 규칙이 다르고, 우연히
//   같은 접미사의 무관한 다른 종목이 있을 수도 있음) — 그래서 실계좌 진입을 "막는" 데 쓰지
//   않고, 화면에 "⚠️ 워런트 의심(확인 필요)" 코멘트만 붙이는 용도로 오너와 합의했다
//   (2026-09-28 대화 — 확실히 막고 싶으면 오너가 직접 종목별로 워런트 티커를 등록하는 2번
//   방식을 나중에 추가하기로 함).
//
// [순수 함수인 이유] 네트워크 호출(실제 시세 조회)은 electron/tool-engine.ts가 하고, 이
//   파일은 "어떤 티커를 시도해볼지" 후보 목록만 만든다 — 테스트로 후보 규칙을 고정한다.
