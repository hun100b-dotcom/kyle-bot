/** 본주 심볼로부터 흔한 워런트 티커 접미사 후보를 만든다(미국 시장 관행 기준). */
export function guessWarrantTickers(symbol: string): string[] {
  const base = symbol.trim().toUpperCase();
  if (!base) return [];
  // 흔한 순서대로: SPAC·소형주에서 자주 보이는 표기들.
  return [`${base}W`, `${base}.WS`, `${base}-WT`, `${base}WS`];
}
